def union_law(A, axes, F):
    union = {}
    info = {}
    for nm, s in axes.items():
        spaces, full = eigen_decomposition(A, s, F)
        one = spaces.get(Q(1), [])
        prim = len(one) == 1 and in_span(s, one)
        info[nm] = (full, prim, {str(l): len(v) for l, v in spaces.items()})
        real = realized_fusion(A, s, spaces)
        for (l, m), occ in real.items():
            union.setdefault(tuple(sorted((l, m))), set()).update(occ)
    return info, {f"{k[0]}*{k[1]}": sorted(str(t) for t in v) for k, v in sorted(union.items())}

def report(name, A, axes, F):
    print("=====", name, "dim", A.n)
    print("commutative", A.is_commutative(), "; idempotents", all(A.mul(s, s) == s for s in axes.values()))
    info, law = union_law(A, axes, F)
    for nm, (full, prim, dims) in info.items():
        print(f"  axis {nm}: semisimple/spectrum-in-F {full}, primitive {prim}, eigen-dims {dims}")
    print("  realised law:", law)
    X = list(axes.values())
    print("  dim <<X>> =", len(subalgebra_generated(A, X)))
    names = list(axes)
    edges = [(p, q) for i, p in enumerate(names) for q in names[i+1:] if not is_zero(A.mul(axes[p], axes[q]))]
    print("  Delta edges:", edges)
    for nm, s in axes.items():
        print(f"  dim I_{nm} =", len(ideal_generated(A, [s])))
    return law

