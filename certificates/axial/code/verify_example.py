# Second, separately written verification of the scout's example (round 7, axial task).
# A = span(a, b, x, c) over Q, eta = 1/3:
#   a^2=a, b^2=b, x^2=x, c^2=c,
#   ab=(eta/2)(a+b-x), ax=(eta/2)(a+x-b), bx=(eta/2)(b+x-a)      [Matsuo algebra 3C(eta)]
#   ca=cb=0, cx=eta(x-a-b).
# X = {a, b, c}.  Fusion law F = {1, 0, eta} with
#   1*1={1}, 1*0={}, 1*eta={eta}, 0*0={1,0,eta}, 0*eta={1,0,eta}, eta*eta={1,0}.
# Everything below is exact (fractions.Fraction); no sympy.
import sys
from fractions import Fraction as Q
from itertools import product
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from axial_tools import *

def build(eta, lam=None):
    if lam is None: lam = eta
    n = 4; A_, B_, X_, C_ = 0, 1, 2, 3
    def v(**d):
        idx = {'a': 0, 'b': 1, 'x': 2, 'c': 3}
        return vec(n, {idx[k]: Q(val) for k, val in d.items()})
    T = [[None] * n for _ in range(n)]
    def setp(i, j, w): T[i][j] = w; T[j][i] = w
    h = Q(eta) / 2
    setp(A_, A_, v(a=1)); setp(B_, B_, v(b=1)); setp(X_, X_, v(x=1)); setp(C_, C_, v(c=1))
    setp(A_, B_, scale(h, v(a=1, b=1, x=-1)))
    setp(A_, X_, scale(h, v(a=1, x=1, b=-1)))
    setp(B_, X_, scale(h, v(b=1, x=1, a=-1)))
    setp(C_, A_, v()); setp(C_, B_, v())
    setp(C_, X_, scale(Q(lam), v(x=1, a=-1, b=-1)))
    return Alg(T, names=['a', 'b', 'x', 'c'])

eta = Q(1, 3)
A = build(eta)
a, b, x, c = A.basis()
F = [Q(1), Q(0), eta]
STAR = {
    (Q(1), Q(1)): {Q(1)}, (Q(1), Q(0)): set(), (Q(1), eta): {eta},
    (Q(0), Q(0)): {Q(1), Q(0), eta}, (Q(0), eta): {Q(1), Q(0), eta},
    (eta, eta): {Q(1), Q(0)},
}
def star(l, m):
    return STAR.get((l, m), STAR.get((m, l)))

out = []
def rep(*s):
    line = " ".join(str(t) for t in s); print(line); out.append(line)

rep("== structure ==")
rep("commutative:", A.is_commutative())
for nm, s in [('a', a), ('b', b), ('c', c)]:
    rep(f"{nm}^2 == {nm}:", A.mul(s, s) == s, " nonzero:", not is_zero(s))

rep("== eigen-decompositions (candidate eigenvalues F = {1, 0, 1/3}) ==")
axes = {'a': a, 'b': b, 'c': c}
decomp = {}
for nm, s in axes.items():
    spaces, full = eigen_decomposition(A, s, F)
    decomp[nm] = spaces
    rep(f"ad_{nm}: diagonalizable with spectrum in F: {full};",
        {str(l): [A.show(v) for v in vs] for l, vs in spaces.items()})
    # independent check via characteristic polynomial: det(tI - ad_s) = prod (t - lam)^{m_lam}
    cp = charpoly(A.ad(s))
    # expected polynomial
    expected = [Q(1)]
    for l, vs in spaces.items():
        for _ in vs:
            expected = [x - l * y for x, y in zip(expected + [Q(0)], [Q(0)] + expected)]
    rep(f"   charpoly(ad_{nm}) =", [str(t) for t in cp], " matches eigen-dims:", cp == expected)
    # primitivity: A_1(s) = span(s)
    one = spaces.get(Q(1), [])
    rep(f"   primitive (dim A_1 = 1 and {nm} in A_1):", len(one) == 1 and in_span(s, one))
    ok, bad, real = check_fusion(A, s, spaces, star)
    rep(f"   fusion law F respected: {ok}; realised rules:",
        {f"{k[0]}*{k[1]}": sorted(str(t) for t in v) for k, v in real.items()})

rep("== realised (minimal) fusion law over all three axes ==")
union = {}
for nm, s in axes.items():
    real = realized_fusion(A, s, decomp[nm])
    for (l, m), occ in real.items():
        key = tuple(sorted((l, m)))
        union.setdefault(key, set()).update(occ)
for k in sorted(union):
    rep(f"   {k[0]}*{k[1]} -> {sorted(str(t) for t in union[k])}")

rep("== generation ==")
G = subalgebra_generated(A, [a, b, c])
rep("dim <<a,b,c>> =", len(G), "(dim A = 4)")
Gab = subalgebra_generated(A, [a, b])
rep("<<a,b>> basis:", [A.show(v) for v in Gab], " contains x:", in_span(x, Gab))
Gc = subalgebra_generated(A, [c])
rep("<<c>> basis:", [A.show(v) for v in Gc])
# irredundancy of X
for nm, gens in [('<<b,c>>', [b, c]), ('<<a,c>>', [a, c])]:
    rep(f"dim {nm} =", len(subalgebra_generated(A, gens)))

rep("== non-annihilation graph on X = {a,b,c} ==")
edges = [(p, q) for p, q in [('a', 'b'), ('a', 'c'), ('b', 'c')] if not is_zero(A.mul(axes[p], axes[q]))]
rep("edges:", edges, "  a*b =", A.show(A.mul(a, b)), "; a*c =", A.show(A.mul(a, c)), "; b*c =", A.show(A.mul(b, c)))

rep("== the component subalgebras do not annihilate each other ==")
rep("x in <<a,b>>:", in_span(x, Gab), "; c*x =", A.show(A.mul(c, x)), " nonzero:", not is_zero(A.mul(c, x)))
rep("x == a + b - 6ab:", x == sub(add(a, b), scale(6, A.mul(a, b))))

rep("== blocks (ideals generated by axes) ==")
Ia = ideal_generated(A, [a]); Ib = ideal_generated(A, [b]); Ic = ideal_generated(A, [c])
rep("I_a:", [A.show(v) for v in Ia]); rep("I_b:", [A.show(v) for v in Ib]); rep("I_c:", [A.show(v) for v in Ic])
rep("I_a == span(a,b,x):", same_space(Ia, [a, b, x]), "; I_a == I_b:", same_space(Ia, Ib),
    "; I_c == A:", len(Ic) == 4, "; I_a proper subset of I_c:", len(Ia) < len(Ic) and all(in_span(v, Ic) for v in Ia))
rep("span(a,b,x) is an ideal:", is_ideal(A, [a, b, x]))

rep("== indecomposability ==")
# projection phi_c onto A_1(c) along A_0(c)+A_eta(c): the linear functional with
# (ad_c^2 - eta ad_c) u = (1-eta) phi_c(u) c
spaces_c = decomp['c']
allv = []; own = []
for l, vs in spaces_c.items():
    for v in vs: allv.append(v); own.append(l)
def phi_c(u):
    co = solve_coords(u, allv)
    k = [i for i in range(len(allv)) if own[i] == Q(1)][0]
    # A_1(c) basis vector is a multiple of c
    return co[k] * allv[k][3] / c[3]
rep("phi_c(a), phi_c(b), phi_c(x), phi_c(c) =", [str(phi_c(v)) for v in (a, b, x, c)])
# identity (ad_c^2 - eta ad_c) u = (1 - eta) phi_c(u) c on the basis
M = A.ad(c)
def adc(u): return matvec(M, u)
ok = all(sub(adc(adc(u)), scale(eta, adc(u))) == scale((1 - eta) * phi_c(u), c) for u in A.basis())
rep("identity ad_c(ad_c u) - eta ad_c u = (1-eta) phi_c(u) c holds on basis:", ok)
rep("=> every ideal I with some u in I, phi_c(u) != 0 contains c, hence I = I_c = A;")
rep("   every proper ideal lies in ker phi_c = span(a,b,x); A is not the sum of its proper ideals.")

rep("== Frobenius forms ==")
forms = frobenius_forms(A)
for Gm in forms:
    rep("form (rows a,b,x,c):", [[str(t) for t in row] for row in Gm])
rep("dimension of the space of Frobenius forms:", len(forms))

# ---------- brute-force cross-check of the ideal lattice modulo p = 7 ----------
rep("== mod-7 cross-check: enumerate all subspaces of F_7^4, find all ideals ==")
p = 7
inv = lambda t: pow(t, p - 2, p)
def modq(fr): return (fr.numerator * inv(fr.denominator % p)) % p
Tp = [[tuple(modq(t) for t in A.T[i][j]) for j in range(4)] for i in range(4)]
def mulp(u, v):
    r = [0] * 4
    for i in range(4):
        if u[i] == 0: continue
        for j in range(4):
            if v[j] == 0: continue
            for k in range(4): r[k] = (r[k] + u[i] * v[j] * Tp[i][j][k]) % p
    return tuple(r)
def rrefp(rows):
    M = [list(r) for r in rows]; r = 0; piv = []
    for col in range(4):
        pr = next((i for i in range(r, len(M)) if M[i][col] % p), None)
        if pr is None: continue
        M[r], M[pr] = M[pr], M[r]
        iv = inv(M[r][col]); M[r] = [(t * iv) % p for t in M[r]]
        for i in range(len(M)):
            if i != r and M[i][col]:
                f = M[i][col]; M[i] = [(s - f * t) % p for s, t in zip(M[i], M[r])]
        piv.append(col); r += 1
    return tuple(tuple(row) for row in M[:r])
# enumerate subspaces as canonical RREF bases: iterate over all sets of up to 4 vectors is too big;
# instead enumerate RREF matrices directly.
def all_rref(k):
    from itertools import combinations
    res = []
    for pivs in combinations(range(4), k):
        free_pos = [(r, col) for r in range(k) for col in range(4) if col > pivs[r] and col not in pivs]
        for vals in product(range(p), repeat=len(free_pos)):
            M = [[0] * 4 for _ in range(k)]
            for r in range(k): M[r][pivs[r]] = 1
            for (r, col), t in zip(free_pos, vals): M[r][col] = t
            res.append(tuple(tuple(row) for row in M))
    return res
E = [tuple(1 if k == i else 0 for k in range(4)) for i in range(4)]
ideals = []
nsub = 0
for k in range(0, 5):
    for Bm in all_rref(k):
        nsub += 1
        ok = True
        for u in Bm:
            for e in E:
                w = mulp(e, u)
                if len(rrefp(list(Bm) + [w])) != k: ok = False; break
            if not ok: break
        if ok: ideals.append(Bm)
rep("subspaces enumerated:", nsub, "; ideals found:", len(ideals))
for Bm in ideals:
    rep("   ideal of dim", len(Bm), ":", Bm)
proper = [Bm for Bm in ideals if len(Bm) < 4]
sumproper = rrefp([v for Bm in proper for v in Bm]) if proper else ()
rep("dim of sum of all proper ideals (mod 7):", len(sumproper), " -> A decomposable mod 7?", len(sumproper) == 4)

