# Verification of the SIMPLE variant (round 7, axial task), exact arithmetic.
# B = span(a, b, x, c) over Q, eta = 1/2:
#   3C(1/2) on (a,b,x):  ab=(1/4)(a+b-x), ax=(1/4)(a+x-b), bx=(1/4)(b+x-a), a^2=a, b^2=b, x^2=x
#   c^2 = c, ca = cb = 0, cx = (1/2)(x-a-b) - (1/4)c.
import sys
from fractions import Fraction as Q
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from axial_tools import *
from simple_variant import E4p
from variants import union_law
from modp_ideals import modp_ideals

eta = Q(1, 2)
A = E4p(eta, eta, Q(-1, 4))
a, b, x, c = A.basis()
out = []
def rep(*s):
    line = " ".join(str(t) for t in s); print(line); out.append(line)
rep("products: a*b =", A.show(A.mul(a,b)), "; c*x =", A.show(A.mul(c,x)), "; c*a =", A.show(A.mul(c,a)), "; c*b =", A.show(A.mul(c,b)))
F = [Q(1), Q(0), eta]
STAR = {(Q(1),Q(1)):{Q(1)}, (Q(1),Q(0)):set(), (Q(1),eta):{eta},
        (Q(0),Q(0)):{Q(1),Q(0),eta}, (Q(0),eta):{Q(1),Q(0),eta}, (eta,eta):{Q(1),Q(0)}}
star = lambda l, m: STAR.get((l, m), STAR.get((m, l)))
for nm, s in [('a',a),('b',b),('c',c)]:
    spaces, full = eigen_decomposition(A, s, F)
    one = spaces.get(Q(1), [])
    ok, bad, real = check_fusion(A, s, spaces, star)
    cp = charpoly(A.ad(s))
    rep(f"axis {nm}: idempotent {A.mul(s,s)==s}; semisimple, spectrum in F: {full}; primitive: {len(one)==1 and in_span(s, one)};",
        "eigenspaces:", {str(l): [A.show(v) for v in vs] for l, vs in spaces.items()}, "; charpoly:", [str(t) for t in cp],
        "; fusion law J+(1/2) respected:", ok)
info, law = union_law(A, {'a':a,'b':b,'c':c}, F)
rep("realised law:", law)
rep("dim <<a,b,c>> =", len(subalgebra_generated(A, [a,b,c])), "; <<a,b>> =", [A.show(v) for v in subalgebra_generated(A,[a,b])])
rep("Delta edges:", [(p,q) for p,q in [('a','b'),('a','c'),('b','c')] if not is_zero(A.mul(dict(a=a,b=b,c=c)[p], dict(a=a,b=b,c=c)[q]))])
rep("x in <<a,b>> and c*x != 0:", in_span(x, subalgebra_generated(A,[a,b])), not is_zero(A.mul(c,x)))

# multiplication algebra M(A): associative algebra generated by ad_a, ad_b, ad_x, ad_c
def mm(P, R):
    n = len(P); return [[sum((P[i][k]*R[k][j] for k in range(n)), Q(0)) for j in range(n)] for i in range(n)]
def flat(M): return tuple(t for row in M for t in row)
gens = {'a': A.ad(a), 'b': A.ad(b), 'x': A.ad(x), 'c': A.ad(c)}
words = {nm: M for nm, M in gens.items()}
span = span_basis([flat(M) for M in words.values()])
frontier = dict(words)
for length in range(2, 6):
    new = {}
    for w, M in frontier.items():
        for g, G in gens.items():
            W = mm(G, M)   # apply M first then G  (word g.w)
            new[g + w] = W
    allf = [flat(M) for M in new.values()]
    span2 = span_basis(span + allf)
    rep(f"words of length <= {length}: dim span = {len(span2)}")
    words.update(new); frontier = new; span = span2
    if len(span) == 16: break
rep("dim M(A) over Q =", len(span), "(16 means M(A) = End(A), hence A has no proper nonzero ideal: simple)")

# explicit certificate: express each matrix unit E_ij as a Q-combination of words (length <= L)
names = list(words.keys()); mats = [flat(words[w]) for w in names]
# choose an independent subset
chosen = []; chosen_names = []
for nm, f in zip(names, mats):
    if rank(chosen + [f]) > len(chosen):
        chosen.append(f); chosen_names.append(nm)
    if len(chosen) == 16: break
rep("basis words of M(A):", chosen_names)
cert = {}
for i in range(4):
    for j in range(4):
        Eij = tuple(Q(1) if (r == i and s == j) else Q(0) for r in range(4) for s in range(4))
        co = solve_coords(Eij, chosen)
        cert[(i, j)] = {chosen_names[k]: co[k] for k in range(16) if co[k] != 0}
rep("E_00 (e_a coefficient projector) =", {k: str(v) for k, v in cert[(0,0)].items()})
# sanity: verify all 16 identities exactly
okc = True
for (i, j), comb in cert.items():
    S = [Q(0)] * 16
    for w, co in comb.items():
        f = flat(words[w]); S = [s + co * t for s, t in zip(S, f)]
    Eij = [Q(1) if (r == i and s == j) else Q(0) for r in range(4) for s in range(4)]
    okc = okc and S == Eij
rep("all 16 matrix-unit identities verified:", okc)
import json
json.dump({f"{i}{j}": {w: str(v) for w, v in comb.items()} for (i, j), comb in cert.items()},
          open(__file__.rsplit('/', 2)[0] + '/logs/simple_certificate.json', 'w'), indent=1)

for p in (5, 7, 11, 13):
    ids = modp_ideals(A, p)
    rep(f"mod {p}: ideal dimensions", sorted(len(I) for I in ids))
rep("Frobenius forms (dimension of space):", len(frobenius_forms(A)))
with open(__file__.rsplit('/', 2)[0] + '/logs/verify_simple.out', 'w') as f:
    f.write("\n".join(out) + "\n")
