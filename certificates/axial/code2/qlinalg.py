def charpoly_FL(M):
    """det(xI - M) by the Faddeev-LeVerrier recursion (exact).  c[i] = coeff of x^i."""
    n = len(M)
    I = mat_id(n)
    c = [ZERO] * (n + 1)
    c[n] = ONE
    Mk = [[ZERO] * n for _ in range(n)]
    for k in range(1, n + 1):
        Mk = mat_add(mat_mul(M, Mk), mat_scale(c[n - k + 1], I))
        AM = mat_mul(M, Mk)
        c[n - k] = -sum((AM[i][i] for i in range(n)), ZERO) / k
    return c


def divide_linear(c, lam):
    """Divide sum c_i x^i by (x - lam); returns (quotient coeffs, remainder)."""
    n = len(c) - 1
    q = [ZERO] * n
    r = c[n]
    for i in range(n - 1, -1, -1):
        q[i] = r
        r = c[i] + r * lam
    return q, r


def root_multiplicity(c, lam):
    c = list(c)
    m = 0
    while len(c) > 1:
        q, r = divide_linear(c, lam)
        if r != 0:
            break
        m += 1
        c = q
    return m


def poly_str(c):
    terms = []
    for i in range(len(c) - 1, -1, -1):
        a = c[i]
        if a == 0:
            continue
        mon = "" if i == 0 else ("x" if i == 1 else "x^%d" % i)
        if mon == "":
            s = str(a)
        elif a == 1:
            s = mon
        elif a == -1:
            s = "-" + mon
        else:
            s = "%s*%s" % (a, mon)
        terms.append(s)
    return (" + ".join(terms)).replace("+ -", "- ") if terms else "0"


