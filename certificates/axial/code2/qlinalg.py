# -*- coding: utf-8 -*-
"""
qlinalg.py -- exact linear algebra over Q and over GF(p), and a small class for
finite-dimensional commutative (not necessarily associative) algebras over Q.

Independent implementation (written from the mathematical specification only).
All rationals are fractions.Fraction; every matrix handed to the row reducer is
type-checked, so a stray float raises immediately.  No floating point anywhere.
"""
import itertools
from fractions import Fraction as Fr

ZERO = Fr(0)
ONE = Fr(1)


# ---------------------------------------------------------------------------
# exact linear algebra over Q
# ---------------------------------------------------------------------------

def _check_exact(rows):
    for r in rows:
        for x in r:
            if not isinstance(x, Fr):
                raise TypeError("non-Fraction entry %r (type %s)" % (x, type(x)))


def rref(rows):
    """Reduced row echelon form over Q: returns (list of nonzero rows, pivot columns)."""
    A = [list(r) for r in rows]
    _check_exact(A)
    if not A:
        return [], []
    m, n = len(A), len(A[0])
    piv, r = [], 0
    for c in range(n):
        p = None
        for i in range(r, m):
            if A[i][c] != 0:
                p = i
                break
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        inv = ONE / A[r][c]
        A[r] = [x * inv for x in A[r]]
        for i in range(m):
            if i != r and A[i][c] != 0:
                f = A[i][c]
                A[i] = [x - f * y for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
        if r == m:
            break
    return A[:r], piv


def span(vectors):
    """Canonical basis (RREF rows, tuple of tuples) of the span of the vectors.
    Two subspaces are equal iff their canonical bases are equal."""
    vs = [list(v) for v in vectors]
    if not vs:
        return tuple()
    R, _ = rref(vs)
    return tuple(tuple(r) for r in R)


def contains(W, v):
    """Is v in the subspace with canonical basis W?"""
    if not any(x != 0 for x in v):
        return True
    if not W:
        return False
    return len(span(list(W) + [v])) == len(W)


def is_subspace(W1, W2):
    """span W1 inside span W2 ?"""
    return all(contains(W2, v) for v in W1)


def nullspace(rows, n):
    """Canonical basis of {x in Q^n : R x = 0} for the matrix with the given rows."""
    rows = [list(r) for r in rows if any(x != 0 for x in r)]
    if not rows:
        return span([[ONE if i == j else ZERO for j in range(n)] for i in range(n)])
    R, piv = rref(rows)
    free = [j for j in range(n) if j not in piv]
    out = []
    for f in free:
        x = [ZERO] * n
        x[f] = ONE
        for i, pc in enumerate(piv):
            x[pc] = -R[i][f]
        out.append(x)
    return span(out) if out else tuple()


def annihilator(W, n):
    """Canonical basis of W^perp = {y : sum_i y_i w_i = 0 for all w in W}."""
    return nullspace(list(W), n)


def intersect(Ws, n):
    rows = []
    for W in Ws:
        rows += [list(y) for y in annihilator(W, n)]
    return nullspace(rows, n)


def ssum(Ws):
    vs = []
    for W in Ws:
        vs += [list(w) for w in W]
    return span(vs)


def coords(Bvecs, w):
    """Coordinates of w w.r.t. the linearly independent list Bvecs (exact solve)."""
    k, n = len(Bvecs), len(w)
    rows = [[Bvecs[i][r] for i in range(k)] + [w[r]] for r in range(n)]
    R, piv = rref(rows)
    if k in piv:
        raise ValueError("vector not in span")
    c = [ZERO] * k
    for i, pc in enumerate(piv):
        c[pc] = R[i][k]
    return c


def mat_id(n):
    return [[ONE if i == j else ZERO for j in range(n)] for i in range(n)]


def mat_mul(A, B):
    m, k, n = len(A), len(B), len(B[0])
    return [[sum((A[i][t] * B[t][j] for t in range(k)), ZERO) for j in range(n)]
            for i in range(m)]


def mat_add(A, B):
    return [[x + y for x, y in zip(r, s)] for r, s in zip(A, B)]


def mat_sub(A, B):
    return [[x - y for x, y in zip(r, s)] for r, s in zip(A, B)]


def mat_scale(c, A):
    return [[c * x for x in r] for r in A]


def mat_vec(A, v):
    return tuple(sum((a * x for a, x in zip(r, v)), ZERO) for r in A)


def is_zero_mat(A):
    return all(x == 0 for r in A for x in r)


def transpose(A):
    return [list(c) for c in zip(*A)]


def colspace(A):
    return span(transpose(A))


def rank(A):
    return len(span(A))


def flat(A):
    return tuple(x for r in A for x in r)


def unflat(v, n):
    return [list(v[i * n:(i + 1) * n]) for i in range(n)]


def matrix_algebra_generated(gens, n):
    """Canonical basis (as flattened n*n vectors) of the unital associative algebra
    generated by the n x n matrices `gens` (span of all words, closure under
    left multiplication by generators)."""
    B = span([flat(mat_id(n))] + [flat(g) for g in gens])
    while True:
        new = [list(b) for b in B] + [list(flat(mat_mul(g, unflat(b, n))))
                                      for g in gens for b in B]
        B2 = span(new)
        if len(B2) == len(B):
            return B2
        B = B2


