class Algebra:
    """Commutative algebra over Q with basis `labels`; `products` maps an unordered
    pair of labels (given once) to a dict {label: coefficient}; unlisted products
    of basis vectors are 0."""

    def __init__(self, name, labels, products):
        self.name = name
        self.labels = list(labels)
        self.n = n = len(self.labels)
        self.idx = {l: i for i, l in enumerate(self.labels)}
        z = tuple([ZERO] * n)
        T = [[z for _ in range(n)] for _ in range(n)]
        seen = set()
        for (p, q), comb in products.items():
            i, j = self.idx[p], self.idx[q]
            key = (min(i, j), max(i, j))
            if key in seen:
                raise ValueError("product %s*%s specified twice" % (p, q))
            seen.add(key)
            v = self.vec(comb)
            T[i][j] = v
            T[j][i] = v
        self.T = T
        self.basis = [tuple(ONE if k == i else ZERO for k in range(n)) for i in range(n)]

    def vec(self, comb):
        v = [ZERO] * self.n
        for l, c in comb.items():
            if isinstance(c, float):
                raise TypeError("float coefficient")
            v[self.idx[l]] += Fr(c)
        return tuple(v)

    def e(self, l):
        return self.basis[self.idx[l]]

    def mul(self, u, v):
        n = self.n
        w = [ZERO] * n
        for i in range(n):
            if u[i] == 0:
                continue
            for j in range(n):
                if v[j] == 0:
                    continue
                c = u[i] * v[j]
                t = self.T[i][j]
                for k in range(n):
                    if t[k] != 0:
                        w[k] += c * t[k]
        return tuple(w)

    def ad(self, u):
        """Matrix of ad_u : v -> u*v (column j = u*e_j)."""
        cols = [self.mul(u, b) for b in self.basis]
        return [[cols[j][i] for j in range(self.n)] for i in range(self.n)]

    def fmt(self, v):
        terms = []
        for l, c in zip(self.labels, v):
            if c == 0:
                continue
            if c == 1:
                terms.append(l)
            elif c == -1:
                terms.append("-" + l)
            else:
                terms.append("%s*%s" % (c, l))
        if not terms:
            return "0"
        return " + ".join(terms).replace("+ -", "- ")

    def fmt_space(self, W):
        if not W:
            return "0"
        return "span(" + ", ".join(self.fmt(w) for w in W) + ")"

    def span_of_labels(self, labels):
        return span([self.e(l) for l in labels])


def subalgebra_generated(A, gens):
    B = span(gens)
    while True:
        new = [list(b) for b in B] + [list(A.mul(u, v)) for u in B for v in B]
        B2 = span(new)
        if len(B2) == len(B):
            return B2
        B = B2


def ideal_generated(A, gens):
    """Smallest ideal containing gens (iterative closure under multiplication by basis)."""
    B = span(gens)
    while True:
        new = [list(b) for b in B] + [list(A.mul(e, v)) for e in A.basis for v in B]
        B2 = span(new)
        if len(B2) == len(B):
            return B2
        B = B2


def mult_algebra(A):
    """Basis (list of n x n matrices) of the unital multiplication algebra M(A),
    generated by the identity and ad_{e_i}."""
    n = A.n
    B = matrix_algebra_generated([A.ad(e) for e in A.basis], n)
    return [unflat(b, n) for b in B]


def ideal_generated_via_MA(MA, gens):
    return span([mat_vec(m, g) for m in MA for g in gens])


def is_ideal(A, J):
    return all(contains(J, A.mul(e, j)) for e in A.basis for j in J)


def is_subalgebra(A, S):
    return all(contains(S, A.mul(u, v)) for u in S for v in S)


def is_ideal_of_subalgebra(A, S, J):
    """J is an ideal of the algebra S (S*J inside J), J inside S."""
    return is_subspace(J, S) and all(contains(J, A.mul(s, j)) for s in S for j in J)


def core(A, W):
    """Largest ideal of A contained in the subspace W (iterate W_{k+1} = {v in W_k :
    e_i v in W_k for all i})."""
    n = A.n
    ads = [A.ad(e) for e in A.basis]
    C = span(W)
    while True:
        L = annihilator(C, n)
        rows = [list(y) for y in L]
        for M in ads:
            for y in L:
                rows.append([sum((y[k] * M[k][j] for k in range(n)), ZERO) for j in range(n)])
        C2 = nullspace(rows, n)
        if C2 == C:
            return C
        C = C2


def quotient_is_full_matrix_algebra(A, L, U):
    """For ideals L inside U: does the unital algebra generated by the induced action
    of the ad_{e_i} on U/L equal End(U/L)?  If yes there is no ideal strictly between."""
    comp, cur = [], [list(l) for l in L]
    for u in U:
        if not contains(span(cur) if cur else tuple(), u):
            comp.append(u)
            cur.append(list(u))
    g = len(comp)
    Bv = list(L) + comp
    mats = []
    for e in A.basis:
        M = [[ZERO] * g for _ in range(g)]
        for j, q in enumerate(comp):
            c = coords(Bv, A.mul(e, q))
            for i in range(g):
                M[i][j] = c[len(L) + i]
        mats.append(M)
    B = matrix_algebra_generated(mats, g)
    return len(B) == g * g, len(B)


# ---------------------------------------------------------------------------
# arithmetic mod p  (sanity checks only)
# ---------------------------------------------------------------------------

def to_p(x, p):
    x = Fr(x)
    if x.denominator % p == 0:
        raise ZeroDivisionError("p divides a denominator")
    return (x.numerator % p) * pow(x.denominator % p, -1, p) % p


def rref_p(rows, p):
    A = [[x % p for x in r] for r in rows]
    if not A:
        return [], []
    m, n = len(A), len(A[0])
    piv, r = [], 0
    for c in range(n):
        pr = None
        for i in range(r, m):
            if A[i][c]:
                pr = i
                break
        if pr is None:
            continue
        A[r], A[pr] = A[pr], A[r]
        inv = pow(A[r][c], -1, p)
        A[r] = [(x * inv) % p for x in A[r]]
        for i in range(m):
            if i != r and A[i][c]:
                f = A[i][c]
                A[i] = [(x - f * y) % p for x, y in zip(A[i], A[r])]
        piv.append(c)
        r += 1
        if r == m:
            break
    return A[:r], piv


def span_p(vectors, p):
    if not vectors:
        return tuple()
    R, _ = rref_p(vectors, p)
    return tuple(tuple(r) for r in R)


def contains_p(W, v, p):
    if not any(x % p for x in v):
        return True
    return len(span_p(list(W) + [list(v)], p)) == len(W)


def mul_p(Tp, u, v, p):
    n = len(u)
    w = [0] * n
    for i in range(n):
        if not u[i]:
            continue
        for j in range(n):
            if not v[j]:
                continue
            c = u[i] * v[j]
            t = Tp[i][j]
            for k in range(n):
                if t[k]:
                    w[k] += c * t[k]
    return tuple(x % p for x in w)


def normalized_vectors(k, p):
    """All nonzero vectors of GF(p)^k whose first nonzero entry is 1."""
    for lead in range(k):
        for rest in itertools.product(range(p), repeat=k - lead - 1):
            yield (0,) * lead + (1,) + rest


def modp_all_ideals(A, V, p):
    """All ideals (over GF(p)) of the algebra V = span(V) (a subalgebra of A given by a
    Q-basis, reduced mod p); computed as all sums of principal ideals."""
    n = A.n
    Tp = [[[to_p(x, p) for x in A.T[i][j]] for j in range(n)] for i in range(n)]
    Vp = [tuple(to_p(x, p) for x in v) for v in V]
    Vs = span_p([list(v) for v in Vp], p)
    assert len(Vs) == len(V), "reduction mod p lost rank"
    for u in Vp:
        for w in Vp:
            assert contains_p(Vs, mul_p(Tp, u, w, p), p), "V not closed mod p"
    k = len(Vp)
    principals = set()
    count = 0
    for c in normalized_vectors(k, p):
        count += 1
        v = [sum(c[i] * Vp[i][t] for i in range(k)) % p for t in range(n)]
        B = span_p([v], p)
        while len(B) < k:
            new = [list(b) for b in B] + [list(mul_p(Tp, s, b, p)) for s in Vp for b in B]
            B2 = span_p(new, p)
            if len(B2) == len(B):
                break
            B = B2
        principals.add(B)
    ideals = set(principals)
    ideals.add(tuple())
    changed = True
    while changed:
        changed = False
        cur = list(ideals)
        for I1 in cur:
            for I2 in cur:
                K = span_p([list(x) for x in I1] + [list(x) for x in I2], p)
                if K not in ideals:
                    ideals.add(K)
                    changed = True
    assert count == (p ** k - 1) // (p - 1)
    return sorted(ideals, key=lambda J: (len(J), J)), Vs, count, len(principals)


def fmt_p(labels, v):
    terms = []
    for l, c in zip(labels, v):
        if c == 0:
            continue
        terms.append(l if c == 1 else "%d*%s" % (c, l))
    return " + ".join(terms) if terms else "0"
