"""Generate Lean lemmas certifying the vertex inequalities of prove_fd.py (Lemmas FD1/FD2 of PROOF.md).

For every vertex check of prove_fd.py (137 checks), every region ('big': P = 4+s, Q = 2+t; 'p3': P = 2, Q = 4+t)
and every min/max branch, the branch value val(P,Q) (a rational function) must be > 0 on the region.  This is
exactly the content of logs/certificates.txt (325 polynomials).  Each is emitted as a Lean theorem

    theorem cert_<k> {P Q : ℝ} (hP : 4 ≤ P) (hQ : 2 ≤ Q) : 0 < val(P, Q)          (region big)
    theorem cert_<k> {Q : ℝ} (hQ : 4 ≤ Q) : 0 < val(2, Q)                         (region p3)

proved by the substitution P = 4 + u², Q = 2 + v² (resp. Q = 4 + v²), `field_simp; ring` to reach N(u,v)/D(v)
(N, D computed here, with nonnegative coefficients) and `positivity`.
"""
import sys, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import sympy as sp
import prove_fd as pf

P, Q = pf.P, pf.Q
u, v = sp.symbols('u v', real=True)

records = []
def fake_check(name, expr_fn, regions=('big', 'p3')):
    # evaluate the branches NOW: the lambdas of prove_fd.py capture the loop variable `dev` by reference
    records.append((name, [sp.sympify(x) for x in pf.branches(expr_fn)], tuple(regions)))
    return True
pf.check = fake_check
pf.results.clear()
pf.run_FD1(); pf.run_FD2()

def lean_str(e):
    s = sp.sstr(e, order='none')
    s = s.replace('**', '^')
    return s

def poly_str(e, gens):
    """expanded polynomial with nonnegative coefficients, printed for Lean (u^2, v^2 powers)."""
    p = sp.Poly(sp.expand(e), *gens)
    terms = []
    for mon, c in zip(p.monoms(), p.coeffs()):
        assert c > 0, (e, c)
        assert c == int(c)
        fac = [str(int(c))]
        for g, k in zip(gens, mon):
            if k == 1: fac.append(str(g))
            elif k > 1: fac.append(f"{g} ^ {k}")
        terms.append(" * ".join(fac))
    return " + ".join(terms) if terms else "0"

def certificate(val, region):
    if region == 'big':
        e = val.subs({P: 4 + u**2, Q: 2 + v**2}, simultaneous=True)
    else:
        e = val.subs({P: 2, Q: 4 + v**2}, simultaneous=True)
    e = sp.together(sp.expand(e))
    num, den = sp.fraction(e)
    num = sp.expand(num); den = sp.expand(den)
    lc = sp.Poly(den, u, v).LC()
    if lc < 0:
        num, den = -num, -den
    return poly_str(num, (u, v)), poly_str(den, (u, v))

def safe(name):
    s = re.sub(r'[^A-Za-z0-9]+', '_', name).strip('_')
    return s

def main(outdir, nfiles=6):
    lemmas = []
    count = 0
    for name, vals, regions in records:
        for reg in regions:
            for bi, val in enumerate(vals):
                val = sp.sympify(val)
                N, D = certificate(val, reg)
                lname = f"cert_{safe(name)}_{reg}_{bi}"
                if reg == 'big':
                    stmt_e = lean_str(val)
                    sub_e = lean_str(val.subs({P: sp.Symbol('PP'), Q: sp.Symbol('QQ')}, simultaneous=True)) \
                        .replace('PP', '(4 + u ^ 2)').replace('QQ', '(2 + v ^ 2)')
                    txt = (f"theorem {lname} {{P Q : ℝ}} (hP : 4 ≤ P) (hQ : 2 ≤ Q) :\n"
                           f"    0 < {stmt_e} := by\n"
                           f"  obtain ⟨u, rfl⟩ := exists_add_sq hP\n"
                           f"  obtain ⟨v, rfl⟩ := exists_add_sq hQ\n"
                           f"  rw [show {sub_e} =\n      ({N}) / ({D}) by\n    field_simp <;> ring]\n"
                           f"  positivity\n")
                else:
                    val2 = val.subs(P, 2)
                    stmt_e = lean_str(val2)
                    sub_e = lean_str(val2.subs(Q, sp.Symbol('QQ'))).replace('QQ', '(4 + v ^ 2)')
                    txt = (f"theorem {lname} {{Q : ℝ}} (hQ : 4 ≤ Q) :\n"
                           f"    0 < {stmt_e} := by\n"
                           f"  obtain ⟨v, rfl⟩ := exists_add_sq hQ\n"
                           f"  rw [show {sub_e} =\n      ({N}) / ({D}) by\n    field_simp <;> ring]\n"
                           f"  positivity\n")
                lemmas.append((lname, txt))
                count += 1
    print("total certificate lemmas:", count, "from", len(records), "vertex checks")
    names = [l for l, _ in lemmas]
    assert len(set(names)) == len(names), "duplicate names"
    chunks = [lemmas[i::nfiles] for i in range(nfiles)]
    for i, ch in enumerate(chunks):
        with open(os.path.join(outdir, f"ICGEqualParityBCert{i+1}.lean"), "w") as f:
            f.write("import Mathlib\nimport Research.ICGEqualParityBCol\n\nset_option autoImplicit false\nset_option linter.unnecessarySeqFocus false\n\n")
            f.write(f"/-! Generated by `work/round6/equal-parity-a2/lean/gen_certs.py` (part {i+1}/{nfiles}):\n"
                    "the vertex certificates of `prove_fd.py` (Lemmas FD1/FD2 of PROOF.md), each proved in Lean.\n"
                    "Independent cross-check; the main proof (`ICGEqualParityBGraph`) does not use them. -/\n\n")
            f.write("noncomputable section\n\nnamespace ICGEqualParityB.Cert\n\nopen ICGEqualParityB\n\n")
            for _, t in ch:
                f.write(t + "\n")
            f.write("end ICGEqualParityB.Cert\n")
    with open(os.path.join(outdir, "cert_names.txt"), "w") as f:
        f.write("\n".join(names) + "\n")

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".", int(sys.argv[2]) if len(sys.argv) > 2 else 6)
