#!/usr/bin/env python3
"""Exploration for HKO Problem 3 (distance-hereditary graphs), random + exhaustive-small tests.

Random connected DH graphs are generated by Bandelt-Mulder one-vertex extensions
(pendant vertex, false twin, true twin) from K1.  For each graph we test:
  FP   : Bandelt-Mulder four-point condition in the sharp form "sorted sums s1<=s2<=s3 satisfy
         s2 == s3, or (s1 == s2 and s3 <= s1 + 2)"   [recollection check]
  H0   : tr > 2 diam  =>  every triametral triple contains a peripheral vertex   [target]
  H1   : tr > 2 diam  =>  every triametral triple contains a diametral pair (Q3)
  H2   : tr > 2 diam  =>  Q4
  P3   : Q3' or Q4 (per graph)
No networkx; BFS distances.
"""
import itertools, random, sys
from collections import deque


def bfs_all(adj):
    n = len(adj)
    D = []
    for s in range(n):
        d = [-1] * n; d[s] = 0; q = deque([s])
        while q:
            u = q.popleft()
            for w in adj[u]:
                if d[w] < 0:
                    d[w] = d[u] + 1; q.append(w)
        D.append(d)
    return D


def random_dh(n, rng, wp=(0.5, 0.25, 0.25)):
    adj = [set()]
    while len(adj) < n:
        v = rng.randrange(len(adj)); u = len(adj)
        op = rng.choices(['pendant', 'false', 'true'], weights=wp)[0]
        if len(adj) == 1 and op == 'false':
            op = 'pendant'   # a false twin of K1 would disconnect the graph
        if op == 'pendant':
            adj.append({v}); adj[v].add(u)
        else:
            nb = set(adj[v])
            if op == 'true':
                nb.add(v)
            adj.append(set(nb))
            for w in nb:
                adj[w].add(u)
    return adj


def fourpoint_ok(D, n):
    for a, b, c, d in itertools.combinations(range(n), 4):
        s = sorted((D[a][b] + D[c][d], D[a][c] + D[b][d], D[a][d] + D[b][c]))
        if not (s[1] == s[2] or (s[0] == s[1] and s[2] <= s[0] + 2)):
            return False
    return True


def props(D, n):
    ecc = [max(r) for r in D]; diam = max(ecc)
    per = {v for v in range(n) if ecc[v] == diam}
    tr = 0; tri = []
    for a, b, c in itertools.combinations(range(n), 3):
        s = D[a][b] + D[a][c] + D[b][c]
        if s > tr: tr = s; tri = [(a, b, c)]
        elif s == tr: tri.append((a, b, c))
    if n < 3: tr = 2 * diam
    q3p = all(any(x in per for x in t) for t in tri)
    q3 = all(any(D[t[i]][t[j]] == diam for i, j in ((0, 1), (0, 2), (1, 2))) for t in tri)
    pairs = [(x, y) for x, y in itertools.combinations(range(n), 2) if D[x][y] == diam]
    q4 = all(any(D[x][y] + D[x][z] + D[y][z] == tr for z in range(n) if z not in (x, y)) for x, y in pairs)
    minper = min(sum(x in per for x in t) for t in tri) if tri else 3
    return dict(diam=diam, tr=tr, q3p=q3p, q3=q3, q4=q4, minper=minper, tri=tri, per=per, ecc=ecc)


if __name__ == '__main__':
    rng = random.Random(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
    trials = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    stats = dict(graphs=0, fp_fail=0, big=0, H0_fail=0, H1_fail=0, H2_fail=0, P3_fail=0)
    minper_hist = {}
    ex = {}
    for t in range(trials):
        n = rng.randint(5, 22)
        wp = rng.choice([(0.5, 0.25, 0.25), (0.7, 0.15, 0.15), (0.34, 0.33, 0.33), (0.6, 0.3, 0.1), (0.6, 0.1, 0.3)])
        adj = random_dh(n, rng, wp)
        D = bfs_all(adj)
        assert all(x >= 0 for r in D for x in r), 'disconnected'
        stats['graphs'] += 1
        if n <= 14 and not fourpoint_ok(D, n):
            stats['fp_fail'] += 1; ex.setdefault('fp', [sorted((u, w) for u in range(n) for w in adj[u] if u < w)])
        p = props(D, n)
        if not (p['q3p'] or p['q4']):
            stats['P3_fail'] += 1; ex.setdefault('P3', (n, sorted((u, w) for u in range(n) for w in adj[u] if u < w)))
        if p['tr'] > 2 * p['diam']:
            stats['big'] += 1
            minper_hist[p['minper']] = minper_hist.get(p['minper'], 0) + 1
            if not p['q3p']:
                stats['H0_fail'] += 1; ex.setdefault('H0', (n, sorted((u, w) for u in range(n) for w in adj[u] if u < w)))
            if not p['q3']:
                stats['H1_fail'] += 1
                ex.setdefault('H1', (n, p['diam'], p['tr'], sorted((u, w) for u in range(n) for w in adj[u] if u < w)))
            if not p['q4']:
                stats['H2_fail'] += 1
                ex.setdefault('H2', (n, p['diam'], p['tr'], sorted((u, w) for u in range(n) for w in adj[u] if u < w)))
    print(stats)
    print('min #peripheral in a triametral triple, over graphs with tr>2diam:', dict(sorted(minper_hist.items())))
    for k, v in ex.items():
        print('example', k, v)
